-- The skill level a node needs and the skill ("Herbalism" or "Mining"), by the name its tooltip
-- shows; nil for anything else. Ore nodes are the veins and deposits.
function D.NodeLevel(name)
    if type(name) ~= "string" then return nil end
    local english = localNames[name] or name
    local node = NODE_LEVELS[english]
    if not node then return nil end
    local ore = english:find("Vein", 1, true) or english:find("Deposit", 1, true)
    return node[2], ore and "Mining" or "Herbalism"
end

