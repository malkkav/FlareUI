local schoolByID
-- The school's English name ("Frost"), or nil for a physical or unknown spell
function D.SpellSchool(spellID)
    if type(spellID) ~= "number" then return nil end
    if not schoolByID then
        schoolByID = {}
        for school, spells in pairs(SCHOOLS) do
            for _, ranks in pairs(spells) do
                for _, id in ipairs(ranks) do schoolByID[id] = school end
            end
        end
    end
    return schoolByID[spellID]
end

