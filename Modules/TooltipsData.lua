    { 40, 45, 11177, { 2, 4 } }, { 46, 50, 11178, { 2, 4 } }, { 51, 55, 14343, { 2, 4 } },
    { 56, 60, NEXUS, { 1, 1 } }, { 61, 99, NEXUS, { 1, 2 } },
}
local NOT_DISENCHANTABLE = { INVTYPE_BODY = true, INVTYPE_TABARD = true }
-- Wands enchanters make.
local CRAFTED_WANDS = { [11287] = true, [11288] = true, [11289] = true, [11290] = true }

local function Band(list, level)
    for _, entry in ipairs(list) do
        if level >= entry[1] and level <= entry[2] then return entry end
    end
end

-- The materials an item can give, most likely first, as item IDs; nil when it can't be disenchanted.
-- Green armour gives mostly dust, green weapons mostly essence; a shard now and then.
function D.Disenchant(itemID, classID, quality, level, equipLoc)
    if classID ~= WEAPON and classID ~= ARMOR then return nil end
    if type(quality) ~= "number" or type(level) ~= "number" then return nil end
    if NOT_DISENCHANTABLE[equipLoc] or CRAFTED_WANDS[itemID] then return nil end
    if quality == UNCOMMON then
        local entry = Band(GREEN, level)
        if not entry then return nil end
        local list = classID == WEAPON and { entry[5], entry[3] } or { entry[3], entry[5] }
        if entry[7] then list[3] = entry[7] end
        return list
    elseif quality == RARE then
        local entry = Band(BLUE, level)
        if not entry then return nil end
        if entry[3] == 14344 then return { 14344, NEXUS } end
        return { entry[3] }
    elseif quality == EPIC then
        local entry = Band(PURPLE, level)
        return entry and { entry[3] } or nil
    end
    return nil
end

-- A material's name: the client's, or the English one while the client hasn't loaded it
function D.MaterialName(itemID)
    local name = C_Item and C_Item.GetItemNameByID and C_Item.GetItemNameByID(itemID)
    if canaccessvalue(name) and type(name) == "string" and name ~= "" then return name end
    if C_Item and C_Item.RequestLoadItemDataByID then pcall(C_Item.RequestLoadItemDataByID, itemID) end
    return MATERIAL_NAMES[itemID]
end
